CREATE TABLE `saicode_column` (
  `id` int unsigned NOT NULL AUTO_INCREMENT COMMENT '主键',
  `table_id` int unsigned DEFAULT NULL COMMENT '所属表ID',
  `column_name` varchar(200) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '字段名称',
  `column_comment` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '字段注释',
  `column_type` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '字段类型',
  `column_width` int DEFAULT '180' COMMENT '列表宽度',
  `default_value` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '默认值',
  `is_pk` smallint DEFAULT '1' COMMENT '1 非主键 2 主键',
  `is_required` smallint DEFAULT '1' COMMENT '1 非必填 2 必填',
  `is_insert` smallint DEFAULT '1' COMMENT '1 非插入字段 2 插入字段',
  `is_edit` smallint DEFAULT '1' COMMENT '1 非编辑字段 2 编辑字段',
  `is_list` smallint DEFAULT '1' COMMENT '1 非列表显示字段 2 列表显示字段',
  `is_query` smallint DEFAULT '1' COMMENT '1 非查询字段 2 查询字段',
  `is_sort` smallint DEFAULT '1' COMMENT '1 非排序 2 排序',
  `query_type` varchar(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT 'eq' COMMENT '查询方式',
  `span` smallint DEFAULT NULL COMMENT '布局',
  `view_type` varchar(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT 'text' COMMENT '页面控件',
  `dict_type` varchar(200) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '字典类型',
  `options` varchar(1000) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '字段其他设置',
  `list_sort` smallint unsigned DEFAULT '0' COMMENT '列表排序',
  `form_sort` smallint unsigned DEFAULT '0' COMMENT '字段排序',
  `remark` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '备注',
  `created_by` int DEFAULT NULL COMMENT '创建者',
  `updated_by` int DEFAULT NULL COMMENT '更新者',
  `create_time` datetime DEFAULT NULL COMMENT '创建时间',
  `update_time` datetime DEFAULT NULL COMMENT '修改时间',
  `delete_time` datetime DEFAULT NULL COMMENT '删除时间',
  PRIMARY KEY (`id`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci ROW_FORMAT=DYNAMIC COMMENT='代码生成业务字段表';
